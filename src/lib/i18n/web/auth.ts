export type AuthMessageKey = keyof (typeof authMessages)["en"];

export function translateAuth(
  locale: SupportedLocale,
  key: AuthMessageKey,
  values?: WebTranslationValues
) {
  return interpolateWebMessage(authMessages[locale][key], values);
}

export function getAuthSportLabel(locale: SupportedLocale, sport: Sport) {
  return translateAuth(locale, `sport.${sport}` as AuthMessageKey);
}

